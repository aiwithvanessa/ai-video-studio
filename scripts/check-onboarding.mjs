import assert from 'node:assert/strict';
import {mkdtempSync,cpSync,mkdirSync,writeFileSync,readFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {resolve} from 'node:path';
import {spawnSync} from 'node:child_process';
const root=mkdtempSync(resolve(tmpdir(),'studio-onboarding-'));
for(const dir of ['scripts','src','brand','docs/briefs'])cpSync(dir,resolve(root,dir),{recursive:true});
mkdirSync(resolve(root,'.local'),{recursive:true});
const state={schemaVersion:1,setup:{complete:true,checks:{}},brand:{status:'complete',evidence:'Prior identity approval'},videos:{},activeVideo:null};
writeFileSync(resolve(root,'.local/studio-state.json'),JSON.stringify(state));
const run=(...args)=>spawnSync(process.execPath,['scripts/studio.mjs',...args],{cwd:root,encoding:'utf8'});
assert.equal(run('reference-intake').status,0);
let saved=JSON.parse(readFileSync(resolve(root,'.local/studio-state.json')));
assert.equal(saved.brand.evidence,state.brand.evidence);assert.equal(saved.style.status,'pending');
assert.notEqual(run('approve-brand','--note','Premature approval').status,0);
const direction=Object.fromEntries(['captions','framing','graphics','pacing','transitions','sound'].map(k=>[k,'Proposed restrained default for '+k]));
const file=resolve(root,'.local/proposal.json');
writeFileSync(file,JSON.stringify({referencesChoice:'declined',references:[],direction,captionMode:'plain'}));
assert.equal(run('style-plan','--file',file).status,0);
const approval=run('approve-brand','--note','Approved current identity and motion direction');assert.equal(approval.status,0);assert(approval.stdout.includes('attach their first video'));
assert.equal(run('onboarding-answer','--step','materials','--value','skip').status,0);
assert.equal(run('onboarding-answer','--step','references','--value','supplied').status,0);
assert.equal(JSON.parse(readFileSync(resolve(root,'.local/studio-state.json'))).onboarding.references,'supplied');
saved=JSON.parse(readFileSync(resolve(root,'.local/studio-state.json')));assert.equal(saved.style.status,'complete');assert.equal(saved.style.identityApproval,'Prior identity approval');
assert.equal(run('brand','--accent','#112233').status,0);
assert.notEqual(run('approve-brand','--note','Stale preview').status,0);
writeFileSync(file,JSON.stringify({referencesChoice:'supplied',references:[],direction,captionMode:'plain'}));
assert.notEqual(run('style-plan','--file',file).status,0);
console.log('Onboarding checks passed: optional reference decline, prior identity preserved, missing/stale style approval blocked, actual proposal approval and incomplete reference records rejected. Structural checks do not establish analysis quality or playback.');
